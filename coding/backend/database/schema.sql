drop policy if exists profiles_select_own on profiles;
create policy profiles_select_own on profiles
  for select using (auth.uid() = user_id);

drop policy if exists profiles_update_own on profiles;
create policy profiles_update_own on profiles
  for update using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists goals_own on goals;
create policy goals_own on goals
  for all using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists runs_own on runs;
create policy runs_own on runs
  for all using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists training_plans_own on training_plans;
create policy training_plans_own on training_plans
  for all using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists training_sessions_own on training_sessions;
create policy training_sessions_own on training_sessions
  for all using (
    exists (
      select 1
      from training_plans
      where training_plans.training_plan_id = training_sessions.training_plan_id
        and training_plans.user_id = auth.uid()
    )
  );

drop policy if exists training_progress_own on training_progress;
create policy training_progress_own on training_progress
  for all using (
    exists (
      select 1
      from training_sessions
      join training_plans on training_plans.training_plan_id = training_sessions.training_plan_id
      where training_sessions.training_session_id = training_progress.training_session_id
        and training_plans.user_id = auth.uid()
    )
  );

drop policy if exists ai_analysis_own on ai_analysis;
